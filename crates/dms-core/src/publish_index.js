(() => {
  "use strict";
  const body = document.getElementById("documents");
  const rows = Array.from(body.querySelectorAll("tr"), (node) => ({
    node,
    folder: node.dataset.folder,
    type: node.dataset.type,
    dateOrder: Number(node.dataset.dateOrder),
    nameOrder: Number(node.dataset.nameOrder),
    search: Array.from(node.querySelectorAll("td"), (cell) => cell.textContent).join(" ").toLowerCase(),
  }));
  const search = document.getElementById("search");
  const sort = document.getElementById("sort");
  const allTypes = document.getElementById("all-types");
  const types = Array.from(document.querySelectorAll("input[data-type]"));
  const folders = Array.from(document.querySelectorAll("button[data-folder]"));
  let folder = "";

  function render() {
    const query = search.value.toLowerCase().trim();
    const enabled = new Set(types.filter((input) => input.checked).map((input) => input.dataset.type));
    const selected = rows.filter((row) =>
      enabled.has(row.type) && row.search.includes(query) &&
      (!folder || row.folder === folder || row.folder.startsWith(`${folder}/`))
    );
    // Ranks are generated by core, preserving its total order (including
    // sub-millisecond release times and Unicode ties) across browser locales.
    selected.sort((a, b) => {
      switch (sort.value) {
        case "date-asc": return b.dateOrder - a.dateOrder;
        case "name-asc": return a.nameOrder - b.nameOrder;
        case "name-desc": return b.nameOrder - a.nameOrder;
        default: return a.dateOrder - b.dateOrder;
      }
    });
    body.replaceChildren(...selected.map((row) => row.node));
    document.getElementById("result-count").textContent = `${selected.length} documents`;
    document.getElementById("empty").hidden = selected.length !== 0;
    allTypes.checked = types.length > 0 && enabled.size === types.length;
    allTypes.indeterminate = enabled.size > 0 && enabled.size < types.length;
    allTypes.disabled = types.length === 0;
  }

  search.addEventListener("input", render);
  sort.addEventListener("change", render);
  for (const input of types) input.addEventListener("change", render);
  allTypes.addEventListener("change", () => {
    for (const input of types) input.checked = allTypes.checked;
    render();
  });
  for (const button of folders) {
    button.addEventListener("click", () => {
      folder = button.dataset.folder;
      for (const other of folders) other.setAttribute("aria-pressed", String(other === button));
      render();
    });
  }
  render();
})();
